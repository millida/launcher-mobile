package net.millida.launcher.core

import net.millida.launcher.core.content.GameVersionRange
import org.junit.Assert.assertEquals
import org.junit.Test

class GameVersionRangeTest {

    private data class Case(val range: String, val game: String, val want: Boolean?, val why: String)

    private fun check(cases: List<Case>) {
        for (case in cases) {
            assertEquals(
                "диапазон «${case.range}» для игры «${case.game}» должен дать ${case.want}. Зачем закреплено: ${case.why}",
                case.want,
                GameVersionRange.satisfies(case.range, case.game),
            )
        }
    }

    @Test
    fun `диапазоны Fabric с операторами сравниваются числами`() {
        check(
            listOf(
                Case(">=1.20", "1.20.1", true, "патч выше нижней границы — мод подходит"),
                Case(">=1.20.2", "1.20.1", false, "игра старее, чем требует мод, — предупреждаем"),
                Case("<1.21", "1.21", false, "строгая верхняя граница не включает саму версию"),
                Case("<=1.21", "1.21", true, "нестрогая граница включает саму версию"),
                Case(">1.20.1", "1.20.1", false, "строго больше — равная версия не подходит"),
                Case("=1.20.1", "1.20.1", true, "одиночный знак равенства читается как точное совпадение"),
                Case("==1.20.1", "1.20.2", false, "двойной знак равенства — точное совпадение"),
                Case(">=1.21.9", "1.21.10", true, "1.21.10 новее 1.21.9: строковое сравнение дало бы ложный отказ"),
                Case(">=1.20.1-beta.2", "1.20.1", true, "хвост пререлиза не ломает сравнение номеров"),
            )
        )
    }

    @Test
    fun `тильда и крышка держат ту же линию 1_x`() {
        check(
            listOf(
                Case("~1.20.1", "1.20.4", true, "патч внутри той же линии подходит"),
                Case("~1.20.1", "1.21", false, "переход на 1.21 — уже другая игра для мода"),
                Case("^1.20", "1.20.6", true, "крышка на Minecraft означает ту же линию 1.20"),
                Case("~1.20.4", "1.20.1", false, "старее нижней границы даже внутри линии — не подходит"),
            )
        )
    }

    @Test
    fun `диапазоны Forge в скобках Maven`() {
        check(
            listOf(
                Case("[1.20.1,1.21)", "1.20.4", true, "внутри полуоткрытого интервала"),
                Case("[1.20.1,1.21)", "1.21", false, "правая круглая скобка исключает 1.21"),
                Case("[1.20.1,1.21)", "1.20", false, "левая квадратная скобка: 1.20 ниже границы"),
                Case("(1.20,]", "1.20", false, "левая круглая скобка исключает саму границу"),
                Case("(1.20,]", "1.20.1", true, "открытый верх пропускает всё новее"),
                Case("[1.20.1]", "1.20.1", true, "одна версия в скобках — точное совпадение"),
                Case("[1.20.1]", "1.20.2", false, "одна версия в скобках не пускает соседний патч"),
                Case("[1.21,1.21.1]", "1.21.1", true, "квадратная правая скобка включает границу (NeoForge)"),
            )
        )
    }

    @Test
    fun `маски и точные версии`() {
        check(
            listOf(
                Case("*", "1.7.10", true, "звёздочка — мод на любую версию"),
                Case("1.20.x", "1.20.4", true, "маска линии пропускает патчи"),
                Case("1.20.x", "1.20", true, "маска линии пропускает саму линию без патча"),
                Case("1.20.x", "1.21", false, "маска не пропускает соседнюю линию"),
                Case("1.2.x", "1.20.1", false, "1.2.x не должна совпадать с 1.20 по префиксу строки"),
                Case("1.20.1", "1.20.1", true, "точная версия совпадает"),
                Case("1.20.1", "1.20.10", false, "точная версия не совпадает с более длинной"),
            )
        )
    }

    @Test
    fun `несколько вариантов через или`() {
        check(
            listOf(
                Case("1.16.5 || 1.20.1", "1.20.1", true, "подходит хотя бы один вариант"),
                Case("1.16.5 || 1.18.2", "1.20.1", false, "ни один вариант не подходит — честный отказ"),
                Case("snapshot || foo", "1.20.1", null, "все варианты непонятны — молчание, а не отказ"),
                Case("foo || 1.18.2", "1.20.1", false, "понятный отказ перевешивает непонятный вариант"),
                Case("foo || >=1.20", "1.20.1", true, "понятное согласие перевешивает непонятный вариант"),
            )
        )
    }

    @Test
    fun `непонятное не превращается в отказ`() {
        check(
            listOf(
                Case("", "1.20.1", null, "мод без диапазона ничего не утверждает"),
                Case("   ", "1.20.1", null, "пробелы — тот же пустой диапазон"),
                Case(">=1.20", "", null, "без версии сборки сравнивать не с чем"),
                Case(">=", "1.20.1", null, "оператор без границы — мусор, а не запрет"),
                Case("[", "1.20.1", null, "обрывок скобки не должен ронять проверку"),
                Case("snapshot", "1.20.1", null, "слово вместо версии — нет мнения"),
            )
        )
    }
}
